const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const out = path.join(__dirname, 'output');
const url = pathToFileURL(path.resolve(__dirname, '../index.html')).href;
let browser;
(async () => {
 browser = await chromium.launch({ headless: true, ...(process.env.GRAPHITOUT_BROWSER_CHANNEL ? { channel: process.env.GRAPHITOUT_BROWSER_CHANNEL } : {}) });
 const context = await browser.newContext();
 await context.addInitScript(() => localStorage.clear());
 const page = await context.newPage();
 const errors = [];
 page.on('pageerror', e => errors.push(e.message));
 const checks = [];
 const record = s => { checks.push(s); console.log('PASS ' + s); };
 for (const width of [1920, 1024, 768, 650, 360, 320]) {
  await page.setViewportSize({ width, height: 900 });
  await page.goto(url);
  await page.waitForTimeout(150);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  const toolbar = await page.locator('.canvas-top').boundingBox();
  const last = await page.locator(width > 950 ? '#search' : '#inspector-toggle').boundingBox();
  assert.ok(last.x + last.width <= toolbar.x + toolbar.width + 1, `Toolbar overflow at ${width}px`);
  if (width < 950) {
   await page.locator('#inspector-toggle').click();
   const panel = await page.locator('#inspector').boundingBox();
   assert.ok(panel.x >= 0 && panel.x + panel.width <= width, `Inspector overflow at ${width}px`);
   await page.locator('#inspector-close').click();
  }
  await page.screenshot({ path: path.join(out, `glass-${width}.png`) });
 }
 record('Floating chrome and details drawers fit desktop, tablet, and 320–650px phone widths');
 await page.setViewportSize({ width: 1440, height: 960 });
 await page.goto(url);
 const initial = await page.locator('#mode-tools').evaluate(el => el.style.getPropertyValue('--tool-offset'));
 await page.locator('#connect-tool').click();
 const connected = await page.locator('#mode-tools').evaluate(el => el.style.getPropertyValue('--tool-offset'));
 assert.notEqual(initial, connected);
 await page.waitForTimeout(400);
 const indicator = await page.locator('#tool-indicator').boundingBox();
 const button = await page.locator('#connect-tool').boundingBox();
 assert.ok(Math.abs(indicator.x - button.x) < 2);
 assert.ok(Math.abs(indicator.width - button.width) < 2);
 const blur = await page.locator('header').evaluate(el => getComputedStyle(el).backdropFilter);
 assert.match(blur, /blur/);
 const nodeOpacity = await page.locator('.graph-node').first().evaluate(el => getComputedStyle(el).backgroundColor);
 assert.equal(nodeOpacity, 'rgb(255, 255, 255)');
 record('Glass controls use real backdrop blur; the tool indicator aligns and graph cards stay opaque');
 await page.locator('#help-btn').click();
 await page.waitForTimeout(400);
 await page.screenshot({ path: path.join(out, 'glass-help.png') });
 await page.locator('[data-close="help-dialog"]').first().click();
 await page.emulateMedia({ reducedMotion: 'reduce', contrast: 'more' });
 assert.equal(await page.locator('#tool-indicator').evaluate(el => getComputedStyle(el).transitionDuration), '0s');
 assert.equal(await page.locator('header').evaluate(el => getComputedStyle(el).backdropFilter), 'none');
 await page.locator('#hand-tool').click();
 assert.equal(await page.locator('#hand-tool').getAttribute('aria-pressed'), 'true');
 await page.screenshot({ path: path.join(out, 'glass-accessibility.png') });
 record('Reduced motion disables springs and increased contrast makes controls solid');
 await page.emulateMedia({ forcedColors: 'active' });
 assert.equal(await page.locator('[data-node]').count(), 7);
 await page.screenshot({ path: path.join(out, 'glass-forced-colors.png') });
 assert.deepEqual(errors, []);
 record('Forced-color rendering remains usable without JavaScript errors');
 await fs.writeFile(path.join(out, 'design-results.json'), JSON.stringify({ checks, errors }, null, 2));
 await browser.close();
})().catch(async error => { console.error(error); if (browser) await browser.close(); process.exitCode = 1; });
